<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use PhpOffice\PhpWord\IOFactory;
use PhpOffice\PhpWord\PhpWord;
use PhpOffice\PhpWord\SimpleType\Jc;

class GenerateLabDocument extends Command
{
    protected $signature = 'kb:generate-lab-doc
                            {--output-dir=app : Directory inside storage/ for output files}';

    protected $description = 'Generate separate Participant and Facilitator Word documents from lab markdown files';

    /** @var array<string, mixed> */
    private array $normal = ['size' => 11, 'name' => 'Calibri'];

    /** @var array<string, mixed> */
    private array $bold = ['size' => 11, 'name' => 'Calibri', 'bold' => true];

    /** @var array<string, mixed> */
    private array $code = ['size' => 10, 'name' => 'Consolas', 'color' => '2d3436'];

    public function handle(): int
    {
        $labs = [
            ['file' => 'dp_lab_1_foundation.md', 'title' => 'Foundation Lab'],
            ['file' => 'dp_lab_2_intermediate.md', 'title' => 'Intermediate Lab'],
            ['file' => 'dp_lab_3_advanced.md', 'title' => 'Advanced Lab'],
            ['file' => 'dp_lab_4_mastery.md', 'title' => 'Mastery Lab'],
        ];

        foreach ($labs as $lab) {
            if (! file_exists(storage_path('app/'.$lab['file']))) {
                $this->error("Missing file: storage/app/{$lab['file']}");

                return self::FAILURE;
            }
        }

        $participantDoc = $this->createDocument();
        $facilitatorDoc = $this->createDocument();

        $this->addTitlePage($participantDoc, 'Demand Planning Lab Series', 'Participant Lab Guide');
        $this->addTitlePage($facilitatorDoc, 'Demand Planning Lab Series', 'Facilitator Guide');

        foreach ($labs as $lab) {
            $this->info("Processing {$lab['title']}...");
            $content = file_get_contents(storage_path('app/'.$lab['file']));

            [$participantMd, $facilitatorMd] = $this->splitDocuments($content);

            $this->renderMarkdownToWord($participantDoc, $participantMd);
            $this->renderMarkdownToWord($facilitatorDoc, $facilitatorMd);
        }

        $outputDir = storage_path($this->option('output-dir'));
        $participantPath = $outputDir.'/DP_Lab_Series_Participant_Guide.docx';
        $facilitatorPath = $outputDir.'/DP_Lab_Series_Facilitator_Guide.docx';

        IOFactory::createWriter($participantDoc, 'Word2007')->save($participantPath);
        IOFactory::createWriter($facilitatorDoc, 'Word2007')->save($facilitatorPath);

        $this->info("Participant guide: {$participantPath}");
        $this->info("Facilitator guide: {$facilitatorPath}");

        return self::SUCCESS;
    }

    private function createDocument(): PhpWord
    {
        $phpWord = new PhpWord;

        $phpWord->addTitleStyle(0, ['size' => 28, 'bold' => true, 'color' => '1a1a2e'], ['alignment' => Jc::CENTER, 'spaceAfter' => 400]);
        $phpWord->addTitleStyle(1, ['size' => 20, 'bold' => true, 'color' => '16213e']);
        $phpWord->addTitleStyle(2, ['size' => 16, 'bold' => true, 'color' => '0f3460']);
        $phpWord->addTitleStyle(3, ['size' => 13, 'bold' => true, 'color' => '333333']);

        return $phpWord;
    }

    private function addTitlePage(PhpWord $phpWord, string $title, string $subtitle): void
    {
        $section = $phpWord->addSection();
        $section->addTextBreak(6);
        $section->addTitle($title, 0);
        $section->addTextBreak(1);
        $tr = $section->addTextRun(['alignment' => Jc::CENTER]);
        $tr->addText($subtitle, ['size' => 18, 'bold' => true, 'color' => '0f3460']);
        $section->addTextBreak(1);
        $tr2 = $section->addTextRun(['alignment' => Jc::CENTER]);
        $tr2->addText('Foundation → Intermediate → Advanced → Mastery', ['size' => 14, 'italic' => true, 'color' => '555555']);
        $section->addTextBreak(2);
        $tr3 = $section->addTextRun(['alignment' => Jc::CENTER]);
        $tr3->addText('Beverage Company Scenario', ['size' => 12, 'color' => '666666']);
        $section->addTextBreak(1);
        $tr4 = $section->addTextRun(['alignment' => Jc::CENTER]);
        $tr4->addText('Generated by SCM Expert Agent — '.date('F j, Y'), ['size' => 10, 'color' => '999999']);
    }

    /**
     * Split markdown content at the DOCUMENT 2 marker.
     *
     * @return array{0: string, 1: string}
     */
    private function splitDocuments(string $content): array
    {
        // Split on the "DOCUMENT 2" heading (facilitator guide)
        $pattern = '/^##\s+DOCUMENT\s+2\s*[:—–-]\s*/mi';

        if (preg_match($pattern, $content, $m, \PREG_OFFSET_CAPTURE)) {
            $participantMd = substr($content, 0, $m[0][1]);
            $facilitatorMd = substr($content, $m[0][1]);

            return [trim($participantMd), trim($facilitatorMd)];
        }

        // Fallback: try splitting on "# Facilitator Guide" heading
        $fallback = '/^#+\s+Facilitator Guide/mi';

        if (preg_match($fallback, $content, $m, \PREG_OFFSET_CAPTURE)) {
            $participantMd = substr($content, 0, $m[0][1]);
            $facilitatorMd = substr($content, $m[0][1]);

            return [trim($participantMd), trim($facilitatorMd)];
        }

        // No split found — put everything in participant
        $this->warn('Could not find facilitator guide marker — entire content goes to participant doc.');

        return [trim($content), ''];
    }

    private function renderMarkdownToWord(PhpWord $phpWord, string $markdown): void
    {
        if (trim($markdown) === '') {
            return;
        }

        $section = $phpWord->addSection(['breakType' => 'nextPage']);
        $inCodeBlock = false;
        $codeBuffer = [];

        foreach (explode("\n", $markdown) as $line) {
            if (preg_match('/^```/', $line)) {
                if ($inCodeBlock) {
                    $codeText = implode("\n", $codeBuffer);
                    if (trim($codeText) !== '') {
                        $section->addText(
                            htmlspecialchars($codeText, ENT_QUOTES | ENT_XML1),
                            $this->code,
                            ['spaceAfter' => 200, 'indentation' => ['left' => 720]]
                        );
                    }
                    $codeBuffer = [];
                    $inCodeBlock = false;
                } else {
                    $inCodeBlock = true;
                }

                continue;
            }

            if ($inCodeBlock) {
                $codeBuffer[] = $line;

                continue;
            }

            $trimmed = trim($line);

            if ($trimmed === '' || preg_match('/^-{3,}$/', $trimmed)) {
                $section->addTextBreak(1);

                continue;
            }

            // Strip the "DOCUMENT 1/2" prefix lines — they served as split markers
            if (preg_match('/^##\s+DOCUMENT\s+\d/i', $trimmed)) {
                continue;
            }

            if (preg_match('/^(#{1,4})\s+(.+)$/', $trimmed, $m)) {
                $level = min(strlen($m[1]), 3);
                $heading = preg_replace('/\*\*(.+?)\*\*/', '$1', $m[2]);
                $section->addTitle(htmlspecialchars($heading, ENT_QUOTES | ENT_XML1), $level);

                continue;
            }

            if (preg_match('/^[-*]\s+(.+)$/', $trimmed, $m)) {
                $textRun = $section->addListItemRun(0);
                $this->addFormattedText($textRun, $m[1]);

                continue;
            }

            if (preg_match('/^\d+\.\s+(.+)$/', $trimmed, $m)) {
                $textRun = $section->addListItemRun(0);
                $this->addFormattedText($textRun, $m[1]);

                continue;
            }

            // Block quotes — render as indented italic
            if (preg_match('/^>\s*(.+)$/', $trimmed, $m)) {
                $textRun = $section->addTextRun(['indentation' => ['left' => 720]]);
                $textRun->addText(
                    htmlspecialchars($m[1], ENT_QUOTES | ENT_XML1),
                    ['size' => 11, 'name' => 'Calibri', 'italic' => true, 'color' => '555555']
                );

                continue;
            }

            $textRun = $section->addTextRun();
            $this->addFormattedText($textRun, $trimmed);
        }
    }

    private function addFormattedText(mixed $textRun, string $text): void
    {
        $parts = preg_split('/(\*\*[^*]+\*\*|`[^`]+`)/', $text, -1, PREG_SPLIT_DELIM_CAPTURE);

        foreach ($parts as $part) {
            if (preg_match('/^\*\*(.+)\*\*$/', $part, $m)) {
                $textRun->addText(htmlspecialchars($m[1], ENT_QUOTES | ENT_XML1), $this->bold);
            } elseif (preg_match('/^`(.+)`$/', $part, $m)) {
                $textRun->addText(htmlspecialchars($m[1], ENT_QUOTES | ENT_XML1), $this->code);
            } elseif ($part !== '') {
                $textRun->addText(htmlspecialchars($part, ENT_QUOTES | ENT_XML1), $this->normal);
            }
        }
    }
}
